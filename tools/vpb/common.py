"""Strict wire format. Cookie values must never become diagnostics."""

import math
import re
import time
from urllib.parse import urlsplit

MAX_PAYLOAD = 512_000
PLATFORMS = {
    'youtube': {'domain': 'youtube.com', 'url': 'https://www.youtube.com/watch?v=pySJJbS-1oo',
                'auth': {'SAPISID', '__Secure-1PAPISID', '__Secure-3PAPISID', 'LOGIN_INFO'}},
    'tiktok': {'domain': 'tiktok.com', 'url': 'https://www.tiktok.com/@_/video/7702437387283991828',
               'auth': {'sessionid', 'sessionid_ss', 'sid_tt'}},
}


class AuthError(Exception):
    """Only a fixed error code, never source exceptions or cookie values."""


def platform_spec(platform):
    if not isinstance(platform, str) or platform not in PLATFORMS:
        raise AuthError('invalid_platform')
    return PLATFORMS[platform]


def scoped_domain(domain, platform):
    base = platform_spec(platform)['domain']
    return isinstance(domain, str) and (domain.lstrip('.') == base or domain.lstrip('.').endswith('.' + base))


def validate_url(platform, url=None):
    spec = platform_spec(platform)
    url = spec['url'] if url is None else url
    if not isinstance(url, str) or len(url) > 2048 or any(c in url for c in '\r\n\t'):
        raise AuthError('invalid_url')
    try:
        parsed = urlsplit(url)
        hosts = {'www.youtube.com', 'youtube.com', 'm.youtube.com', 'youtu.be'} if platform == 'youtube' else {
            'www.tiktok.com', 'tiktok.com', 'm.tiktok.com', 'vm.tiktok.com', 'vt.tiktok.com'}
        if (parsed.scheme != 'https' or parsed.hostname not in hosts or parsed.username or parsed.password
                or parsed.port not in (None, 443)):
            raise AuthError('invalid_url')
    except ValueError:
        raise AuthError('invalid_url') from None
    return url


def validate_cookies(cookies, platform, *, require_auth=True, now=None):
    spec = platform_spec(platform)
    if not isinstance(cookies, list) or not 1 <= len(cookies) <= 500:
        raise AuthError('invalid_cookies')
    now = time.time() if now is None else now
    selected = []
    for cookie in cookies:
        if not isinstance(cookie, dict) or not scoped_domain(cookie.get('domain'), platform):
            raise AuthError('invalid_cookie_domain')
        name, value, path = cookie.get('name'), cookie.get('value'), cookie.get('path', '/')
        if (not isinstance(name, str) or not re.fullmatch(r'[!#$%&\x27*+.^_`|~0-9A-Za-z-]{1,256}', name)
                or not isinstance(value, str) or len(value) > 16384
                or any(c in value for c in '\x00\r\n\t')
                or not isinstance(path, str) or not path.startswith('/') or len(path) > 2048
                or any(c in path for c in '\x00\r\n\t')
                or not re.fullmatch(r'\.?(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,63}', cookie['domain'])
                or not isinstance(cookie.get('secure', False), bool)
                or not isinstance(cookie.get('httpOnly', False), bool)):
            raise AuthError('invalid_cookies')
        expires = cookie.get('expires', -1)
        if (not isinstance(expires, (int, float)) or not math.isfinite(expires)
                or expires > 253402300799):
            raise AuthError('invalid_cookies')
        if expires > 0 and expires <= now:
            continue
        # Partitioned third-party cookies do not have a Netscape representation.
        if cookie.get('partitionKey') or cookie.get('partitionKeyOpaque'):
            continue
        selected.append({'domain': cookie['domain'], 'name': name, 'value': value, 'path': path,
                         'secure': cookie.get('secure', False), 'httpOnly': cookie.get('httpOnly', False),
                         'expires': int(expires) if expires > 0 else 0})
    if not selected or (require_auth and not any(c['name'] in spec['auth'] and c['value'] for c in selected)):
        raise AuthError('login_required')
    return selected


def netscape_bytes(cookies, platform):
    rows = ['# Netscape HTTP Cookie File', '# Generated by vpb; platform-scoped session.']
    for cookie in validate_cookies(cookies, platform):
        domain = ('#HttpOnly_' if cookie['httpOnly'] else '') + cookie['domain']
        rows.append('\t'.join((domain, 'TRUE' if cookie['domain'].startswith('.') else 'FALSE', cookie['path'],
                               'TRUE' if cookie['secure'] else 'FALSE', str(cookie['expires']),
                               cookie['name'], cookie['value'])))
    return ('\n'.join(rows) + '\n').encode('utf-8')
